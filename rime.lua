local JIANPIN_INITIALS = {}
for c in string.gmatch("bpmfdtnlgkhjqxrzcsyw", "%a") do
    JIANPIN_INITIALS[c] = true
end
local JIANPIN_ZERO = { ang = true, eng = true, ai = true, ei = true, ao = true,
    ou = true, an = true, en = true, er = true, ["a"] = true, ["o"] = true, ["e"] = true }

-- 整串可分解为「声母字母 + 零声母全拼音节」序列（≥2 个 token）才算简拼
local function kongtype_is_jianpin(s)
    if #s < 2 then return false end
    local i, tokens = 1, 0
    while i <= #s do
        local c = s:sub(i, i)
        if JIANPIN_INITIALS[c] then
            i = i + 1
            tokens = tokens + 1
        else
            local matched = false
            for len = 3, 1, -1 do
                local t = s:sub(i, i + len - 1)
                if JIANPIN_ZERO[t] then
                    i = i + len
                    tokens = tokens + 1
                    matched = true
                    break
                end
            end
            if not matched then return false end
        end
    end
    return tokens >= 2
end

function kongtype_jianpin_translator(input, seg)
    if kongtype_is_jianpin(input) then
        local entries = KONGTYPE_JIANPIN[input]
        if entries then
            for _, e in ipairs(entries) do
                yield(Candidate("jianpin", seg.start, seg._end, e[1], "〔簡拼〕"))
            end
        end
    end
end
